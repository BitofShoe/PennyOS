function buildLocalLlmAppRoadmap({
  generatedAt = new Date().toISOString(),
  piDetected = false,
  openCodeDetected = false,
} = {}) {
  const buckets = buildBuckets({ piDetected, openCodeDetected });
  return {
    schema_version: 1,
    generated_at: generatedAt,
    project: ROADMAP_PROJECT,
    penny_is_center: true,
    sidecars_are_not_replacements: true,
    buckets,
    do_not_add: [...DO_NOT_ADD],
    safe_next_actions: [...SAFE_NEXT_ACTIONS],
    deferred: [
      'actual sidecar installs',
      'workflow automation live flows',
      'home/camera live integrations',
      'private document RAG ingestion',
      'voice UI wiring',
      'model-serving backend swaps',
      'provider/default model changes',
      'memory promotion',
    ],
  };
}

function normalizeLookup(value = '') {
  return String(value || '').toLowerCase().replace(/[^a-z0-9]+/g, '');
}

function allApps(roadmap = buildLocalLlmAppRoadmap()) {
  return (roadmap.buckets || []).flatMap((bucketItem) => (bucketItem.apps || []).map((item) => ({
    ...item,
    bucket_id: item.bucket_id || bucketItem.bucket_id,
  })));
}

function findLocalLlmApp(roadmap, name) {
  const key = normalizeLookup(name);
  return allApps(roadmap).find((item) => normalizeLookup(item.app_id) === key || normalizeLookup(item.display_name) === key) || null;
}

function shortlistApps(roadmap = buildLocalLlmAppRoadmap()) {
  const priorityRank = { now: 0, next: 1, maybe: 2, defer: 3 };
  return allApps(roadmap)
    .filter((item) => ['now', 'next'].includes(item.priority))
    .sort((a, b) => (priorityRank[a.priority] ?? 9) - (priorityRank[b.priority] ?? 9)
      || String(a.display_name).localeCompare(String(b.display_name)));
}

function patternCards(roadmap = buildLocalLlmAppRoadmap()) {
  return allApps(roadmap).flatMap((item) => (item.patterns_to_steal || []).map((pattern) => ({
    app_id: item.app_id,
    display_name: item.display_name,
    bucket_id: item.bucket_id,
    pattern_to_steal: pattern,
    penny_status: 'candidate_for_review',
  })));
}

function renderRoadmapMarkdown(roadmap = buildLocalLlmAppRoadmap()) {
  const lines = [
    '# Penny Local LLM Apps Roadmap',
    '',
    `Generated: ${roadmap.generated_at}`,
    '',
    'Penny remains the companion/runtime owner. Sidecars are tools, labs, eval surfaces, or pattern sources.',
    '',
    '## Recommended First Trials',
    ...roadmap.safe_next_actions.map((item) => `- ${item}`),
    '',
    '## Buckets',
  ];
  for (const bucketItem of roadmap.buckets || []) {
    lines.push('', `### ${bucketItem.title}`, '', bucketItem.why_interesting, '');
    for (const item of bucketItem.apps || []) {
      lines.push(`- ${item.display_name}: ${item.priority}; ${item.penny_core_status}; ${item.concrete_trial}`);
    }
  }
  lines.push('', '## Do Not Add', ...roadmap.do_not_add.map((item) => `- ${item}`), '');
  return `${lines.join('\n')}\n`;
}

